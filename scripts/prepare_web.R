source(file.path('scripts','bootstrap.R'),encoding='UTF-8')
ami_need(c('shiny','testthat'))
args<-commandArgs(trailingOnly=TRUE)
if(!length(args)&&is.character(getOption('ami_github.step21'))&&length(getOption('ami_github.step21'))==1L)args<-getOption('ami_github.step21')
if(!length(args))stop('Supply the completed Step21 directory: Rscript scripts/prepare_web.R /absolute/path/to/Step21')
local({
  original<-normalizePath(file.path(args[1],'local_only/webapp'),winslash='/',mustWork=TRUE)
  e<-new.env(parent=globalenv());sys.source(file.path(ami_root,'deployment/release_helpers.R'),e)
  # Match the actual successful model export recorded with this source release.
  e$ami_check_release(original,file.path(ami_root,'deployment'))
  out<-file.path(ami_root,'work/webapp');parent<-dirname(out);dir.create(parent,recursive=TRUE,showWarnings=FALSE)
  owner<-file.path(out,'.AMI_REPOSITORY_WEB')
  if(dir.exists(out)&&length(list.files(out,all.files=TRUE,no..=TRUE))&&!file.exists(owner))stop('work/webapp contains unmanaged files. Choose a separate repository copy.')
  stage<-tempfile('web_candidate_',tmpdir=parent);dir.create(stage);on.exit(unlink(stage,recursive=TRUE))
  e$ami_copy_files(original,stage,c('model_30day.rds','model_hospital.rds','model_manifest.csv'))
  e$ami_copy_files(file.path(ami_root,'app'),stage,list.files(file.path(ami_root,'app'),recursive=TRUE))
  e$ami_check_release(stage,file.path(ami_root,'deployment'))
  for(f in c('tests_server.R','tests_release.R','tests_presentation.R'))sys.source(file.path(stage,f),e)
  z<-rbind(e$run_ami_shiny_tests(stage),e$run_ami_release_tests(stage),e$run_ami_presentation_tests(stage))
  stopifnot(nrow(z)==33L,all(z$status=='PASS'))
  writeLines('Frozen model integrity and server checks passed.',file.path(stage,'VALIDATED_LOCAL_PROTOTYPE.txt'))
  z<-rbind(z,e$ami_check_web_entry(stage))
  e$ami_copy_files(stage,out,list.files(stage,recursive=TRUE))
  writeLines('AMI_REPOSITORY_WEB',owner)
  utils::write.csv(z,file.path(parent,'web_checks.csv'),row.names=FALSE)
  cat('Prepared:',out,'\n34 checks passed. Run scripts/launch_web.R.\n')
})
